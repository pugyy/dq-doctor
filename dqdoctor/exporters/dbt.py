"""dbt export (contract -> schema YAML).

Targets dbt >= 1.8: column-level tests use the ``data_tests`` key (the
0.7-era ``tests`` key is deprecated and removed in newer dbt). Range
checks map to ``dbt_utils.expression_is_true``; unmappable rule types are
exported as explicit comments so nothing silently disappears.
"""
from __future__ import annotations

from pathlib import Path

import yaml

from dqdoctor.contract import Contract


def _literal(value) -> str:
    """Render a numeric boundary as a bare number when it parses as one.

    Contract params keep precision as strings (e.g. "99999.99"); dbt
    expressions must compare numerically, so numeric strings are emitted
    unquoted and only genuinely textual values are quoted.
    """
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    text = str(value).strip()
    try:
        float(text)
    except ValueError:
        return "'" + text.replace("'", "''") + "'"
    return text


def export_dbt(contract: Contract) -> str:
    models = []
    notes: list[str] = []
    for table, tr in sorted(contract.tables.items()):
        columns: dict[str, dict] = {}
        for rule in tr.rules:
            if not rule.enabled:
                continue
            entry = columns.setdefault(rule.column, {"name": rule.column, "data_tests": []})
            if rule.type == "not_null":
                entry["data_tests"].append("not_null")
            elif rule.type == "unique":
                entry["data_tests"].append("unique")
            elif rule.type == "accepted_values":
                entry["data_tests"].append({
                    "accepted_values": {
                        "values": [str(v) for v in rule.params.get("values", [])]
                    }
                })
            elif rule.type == "range":
                lo = rule.params.get("min")
                hi = rule.params.get("max")
                if lo is not None:
                    entry["data_tests"].append({
                        "dbt_utils.expression_is_true": {
                            "expression": f"{rule.column} >= {_literal(lo)}"
                        }
                    })
                if hi is not None:
                    entry["data_tests"].append({
                        "dbt_utils.expression_is_true": {
                            "expression": f"{rule.column} <= {_literal(hi)}"
                        }
                    })
            else:
                notes.append(
                    f"# {table}.{rule.column}: rule type '{rule.type}' "
                    f"({rule.id}) has no dbt equivalent and was not exported"
                )
        models.append({
            "name": table,
            "description": "Generated by dq-doctor 1.0",
            "columns": list(columns.values()),
        })
    schema = {"version": 2, "models": models}
    text = yaml.safe_dump(schema, sort_keys=False, allow_unicode=True, width=100)
    header = (
        "# dq-doctor 1.0 export - dbt >= 1.8 (data_tests)\n"
        "# range tests use dbt_utils.expression_is_true: add dbt-utils to packages.yml\n"
    )
    if notes:
        header += "\n".join(notes) + "\n"
    return header + text


def save(contract: Contract, out: Path) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(export_dbt(contract), encoding="utf-8")
    return out
